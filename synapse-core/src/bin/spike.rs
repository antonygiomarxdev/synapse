//! Viability spike: validates vLLM as a Rust-controlled subprocess for MoE inference.
//!
//! This binary is deliberately minimal — no error handling library, no abstractions,
//! no module structure. It answers one question: can we reliably control vLLM workers
//! from Rust via Unix sockets + protobuf?
//!
//! # Usage
//!
//! ```bash
//! cargo run --bin spike -- --test=smoke       # 1 worker, 1 prompt
//! cargo run --bin spike -- --test=sequential  # 1 worker, 100 prompts
//! cargo run --bin spike -- --test=concurrent  # 1 worker, 10 parallel
//! cargo run --bin spike -- --test=multi       # 2 workers, round-robin
//! cargo run --bin spike -- --test=crash       # crash recovery
//! ```
//!
//! See: docs/superpowers/spikes/2026-07-28-vllm-viability-spike.md

