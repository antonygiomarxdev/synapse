#[derive(Debug)]
enum TestKind {
    Smoke,
    Sequential,
    Concurrent,
    Multi,
    Crash,
}

struct Args {
    test: TestKind,
    workers: usize,
    prompts: usize,
    model: String,
}

impl Args {
    fn parse() -> Self {
        let mut test = TestKind::Smoke;
        let mut workers = 1;
        let mut prompts = 100;
        let mut model = "allenai/OLMoE-1B-7B-0924".to_string();

        for arg in std::env::args().skip(1) {
            if let Some(val) = arg.strip_prefix("--test=") {
                test = match val {
                    "smoke" => TestKind::Smoke,
                    "sequential" => TestKind::Sequential,
                    "concurrent" => TestKind::Concurrent,
                    "multi" => TestKind::Multi,
                    "crash" => TestKind::Crash,
                    other => {
                        eprintln!(
                            "Unknown test: {other}. Use: smoke|sequential|concurrent|multi|crash"
                        );
                        std::process::exit(1);
                    }
                };
            } else if let Some(val) = arg.strip_prefix("--workers=") {
                workers = val.parse().unwrap_or(1);
            } else if let Some(val) = arg.strip_prefix("--prompts=") {
                prompts = val.parse().unwrap_or(100);
            } else if let Some(val) = arg.strip_prefix("--model=") {
                model = val.to_string();
            }
        }
        Self { test, workers, prompts, model }
    }
}

// ── Metrics ──────────────────────────────────────────────────────────────────

#[derive(Debug, Default)]
struct Metrics {
    total: u64,
    success: u64,
    failed: u64,
    /// End-to-end latencies (including socket overhead). Nanoseconds.
    e2e_ns: Vec<u64>,
    /// Worker-side latencies (vLLM generate() only). Nanoseconds.
    worker_ns: Vec<u64>,
    tokens_total: u64,
}

impl Metrics {
    fn record(&mut self, e2e: Duration, worker_ms: i64, tokens: u32, is_success: bool) {
        self.total += 1;
        if is_success {
            self.success += 1;
        } else {
            self.failed += 1;
        }
        self.e2e_ns.push(e2e.as_nanos() as u64);
        self.worker_ns.push((worker_ms as u64) * 1_000_000);
        self.tokens_total += tokens as u64;
    }

    fn p50(ns: &[u64]) -> f64 {
        if ns.is_empty() {
            return 0.0;
        }
        let mut sorted = ns.to_vec();
        sorted.sort_unstable();
        let mid = sorted.len() / 2;
        if sorted.len() % 2 == 0 {
            (sorted[mid - 1] + sorted[mid]) as f64 / 2.0
        } else {
            sorted[mid] as f64
        }
    }

    fn p95(ns: &[u64]) -> f64 {
        if ns.is_empty() {
            return 0.0;
        }
        let mut sorted = ns.to_vec();
        sorted.sort_unstable();
        let idx = ((sorted.len() as f64) * 0.95).ceil() as usize - 1;
        let idx = idx.min(sorted.len() - 1);
        sorted[idx] as f64
    }

    fn p99(ns: &[u64]) -> f64 {
        if ns.is_empty() {
            return 0.0;
        }
        let mut sorted = ns.to_vec();
        sorted.sort_unstable();
        let idx = ((sorted.len() as f64) * 0.99).ceil() as usize - 1;
        let idx = idx.min(sorted.len() - 1);
        sorted[idx] as f64
    }

    fn report(&self, label: &str) {
        println!();
        println!("═══ {label} ═══");
        println!("  Total:      {}", self.total);
        println!(
            "  Success:    {} ({:.1}%)",
            self.success,
            self.success as f64 / self.total as f64 * 100.0
        );
        println!("  Failed:     {}", self.failed);
        println!("  Tokens:     {}", self.tokens_total);
        if !self.e2e_ns.is_empty() {
            println!(
                "  E2E (ms):   p50={:.1}  p95={:.1}  p99={:.1}",
                Self::p50(&self.e2e_ns) / 1_000_000.0,
                Self::p95(&self.e2e_ns) / 1_000_000.0,
                Self::p99(&self.e2e_ns) / 1_000_000.0,
            );
        }
        if !self.worker_ns.is_empty() {
            let avg_overhead = self
                .e2e_ns
                .iter()
                .zip(&self.worker_ns)
                .map(|(e, w)| e.saturating_sub(*w))
                .sum::<u64>()
                / self.e2e_ns.len().max(1) as u64;
            println!("  Overhead (ms avg): {:.1}", avg_overhead as f64 / 1_000_000.0);
        }
        if !self.worker_ns.is_empty() {
            println!(
                "  Worker (ms): p50={:.1}  p95={:.1}  p99={:.1}",
                Self::p50(&self.worker_ns) / 1_000_000.0,
                Self::p95(&self.worker_ns) / 1_000_000.0,
                Self::p99(&self.worker_ns) / 1_000_000.0,
            );
        }
    }
}

// ── Worker lifecycle ─────────────────────────────────────────────────────────

/// Socket path for a worker with the given index.
fn socket_path(idx: usize) -> PathBuf {
    std::env::temp_dir().join(format!("synapse-spike-{idx}.sock"))
}

/// Spawn a Python vLLM worker process.
///
/// The worker script receives the socket path and model name as CLI args.
/// It writes "READY\n" to stdout once the model is loaded and the socket
/// is listening.
async fn spawn_worker(idx: usize, model: &str) -> Result<Child, String> {
    let sock = socket_path(idx);
    // Clean up stale socket file if it exists
    let _ = std::fs::remove_file(&sock);

    // Determine the project root (where synapse-runtime lives).
    // cargo sets CARGO_MANIFEST_DIR to the directory of the Cargo.toml being built.
    let project_root = std::env::var("CARGO_MANIFEST_DIR")
        .map(|d| {
            PathBuf::from(d).parent().map(|p| p.to_path_buf()).unwrap_or_else(|| PathBuf::from("."))
        })
        .unwrap_or_else(|_| PathBuf::from("."));

    let pythonpath = project_root.join("synapse-runtime");

    let child = Command::new("python3")
        .arg("-m")
        .arg("synapse_runtime.worker")
        .arg("--socket")
        .arg(sock.to_str().unwrap())
        .arg("--model")
        .arg(model)
        .current_dir(&project_root)
        .env("PYTHONPATH", pythonpath)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::inherit())
        .kill_on_drop(true)
        .spawn()
        .map_err(|e| format!("Failed to spawn worker {idx}: {e}"))?;

    Ok(child)
}

/// Wait for a worker to signal readiness by printing "READY\n" to stdout.
async fn wait_ready(idx: usize, mut child: Child) -> Result<Child, String> {
    let stdout = child.stdout.take().ok_or_else(|| format!("Worker {idx}: no stdout pipe"))?;

    let mut reader = tokio::io::BufReader::new(stdout);
    let mut line = String::new();

    let result = timeout(Duration::from_secs(180), async {
        loop {
            line.clear();
            let n = reader.read_line(&mut line).await?;
            if n == 0 {
                return Err(std::io::Error::new(
                    std::io::ErrorKind::UnexpectedEof,
                    "stdout closed",
                ));
            }
            if line.trim() == "READY" {
                return Ok(());
            }
            // Print any other output as progress
            print!("[worker{idx}] {line}");
        }
    })
    .await;

    match result {
        Ok(Ok(())) => {
            println!("[worker{idx}] READY signal received");
            Ok(child)
        }
        Ok(Err(e)) => Err(format!("Worker {idx} failed before READY: {e}")),
        Err(_) => Err(format!("Worker {idx} timed out waiting for READY (180s)")),
    }
}

/// Connect to a worker's Unix socket with retries.
async fn connect_socket(idx: usize) -> Result<UnixStream, String> {
    let sock = socket_path(idx);
    for attempt in 0..30 {
        // 30 attempts × 500ms = 15s max
        match UnixStream::connect(&sock).await {
            Ok(stream) => {
                println!("[worker{idx}] socket connected ({sock:?})");
                return Ok(stream);
            }
            Err(e)
                if e.kind() == std::io::ErrorKind::NotFound
                    || e.kind() == std::io::ErrorKind::ConnectionRefused =>
            {
                if attempt == 0 {
                    print!("[worker{idx}] waiting for socket");
                }
                print!(".");
                tokio::time::sleep(Duration::from_millis(500)).await;
            }
            Err(e) => return Err(format!("Worker {idx} socket error: {e}")),
        }
    }
    Err(format!("Worker {idx} socket never appeared"))
}

struct Worker {
    idx: usize,
    child: Child,
    stream: UnixStream,
}

impl Worker {
    async fn new(idx: usize, model: &str) -> Result<Self, String> {
        let child = spawn_worker(idx, model).await?;
        let child = wait_ready(idx, child).await?;
        let stream = connect_socket(idx).await?;
        Ok(Self { idx, child, stream })
    }

    /// Kill the worker process (SIGKILL).
    async fn kill(&mut self) -> Result<(), String> {
        println!("[worker{}] KILL signal sent", self.idx);
        self.child.start_kill().map_err(|e| format!("Failed to kill worker {}: {e}", self.idx))
    }
}

// ── Protocol (length-prefixed protobuf over Unix stream) ─────────────────────

/// Send a SpikeRequest and receive a SpikeResponse over a Unix stream.
///
/// Wire format: [4-byte BE length][protobuf payload]
async fn rpc(stream: &mut UnixStream, request: &SpikeRequest) -> Result<SpikeResponse, String> {
    // Serialize request
    let req_bytes = request.encode_to_vec();
    let req_len = (req_bytes.len() as u32).to_be_bytes();

    // Write: length prefix + payload
    stream.write_all(&req_len).await.map_err(|e| format!("write len: {e}"))?;
    stream.write_all(&req_bytes).await.map_err(|e| format!("write body: {e}"))?;

    // Read: 4-byte length prefix
    let mut len_buf = [0u8; 4];
    stream.read_exact(&mut len_buf).await.map_err(|e| format!("read len: {e}"))?;
    let resp_len = u32::from_be_bytes(len_buf) as usize;

    // Sanity check: don't allocate >16MB for a response
    if resp_len > 16 * 1024 * 1024 {
        return Err(format!("Response too large: {resp_len} bytes"));
    }

    // Read payload
    let mut resp_bytes = vec![0u8; resp_len];
    stream.read_exact(&mut resp_bytes).await.map_err(|e| format!("read body: {e}"))?;

    // Deserialize
    SpikeResponse::decode(resp_bytes.as_slice()).map_err(|e| format!("decode response: {e}"))
}

