// ── Test runners ─────────────────────────────────────────────────────────────

/// 1 worker, 1 prompt. Does the thing even work?
async fn test_smoke(worker: &mut Worker) -> Result<Metrics, String> {
    let mut metrics = Metrics::default();
    let prompt = make_prompts(1).into_iter().next().unwrap();

    println!("\n─── Smoke test: 1 prompt ───");
    println!("Prompt: {prompt}");

    let req = SpikeRequest { prompt: prompt.clone(), max_tokens: 64, seed: 42 };
    let start = Instant::now();
    let resp = rpc(&mut worker.stream, &req).await?;
    let elapsed = start.elapsed();

    let ok = resp.error.is_empty() && !resp.text.is_empty();
    metrics.record(elapsed, resp.elapsed_ms, resp.tokens_generated, ok);

    println!("Response: {}", resp.text);
    println!(
        "Tokens: {}, Worker time: {}ms, E2E: {}ms, Error: {:?}",
        resp.tokens_generated,
        resp.elapsed_ms,
        elapsed.as_millis(),
        resp.error
    );

    Ok(metrics)
}

/// 1 worker, N prompts sequentially. Stability baseline.
async fn test_sequential(worker: &mut Worker, prompts: &[String]) -> Result<Metrics, String> {
    let mut metrics = Metrics::default();
    println!("\n─── Sequential test: {} prompts ───", prompts.len());

    for (i, prompt) in prompts.iter().enumerate() {
        let req = SpikeRequest { prompt: prompt.clone(), max_tokens: 64, seed: 42 };
        let start = Instant::now();
        match rpc(&mut worker.stream, &req).await {
            Ok(resp) => {
                let ok = resp.error.is_empty() && !resp.text.is_empty();
                metrics.record(start.elapsed(), resp.elapsed_ms, resp.tokens_generated, ok);
                if i % 10 == 0 {
                    print!(".");
                }
                if !ok {
                    eprintln!("\n[{i}] Worker error: {}", resp.error);
                }
            }
            Err(e) => {
                metrics.record(start.elapsed(), 0, 0, false);
                eprintln!("\n[{i}] RPC error: {e}");
            }
        }
    }
    println!();
    Ok(metrics)
}

/// 1 worker, N prompts sent as fast as possible sequentially.
///
/// This measures the worker's throughput under load. vLLM's internal
/// engine handles continuous batching, so sequential rapid dispatch
/// is a valid proxy for concurrent load at this stage.
/// True multi-connection concurrency requires multiple socket connections,
/// which is a v2 concern.
async fn test_concurrent(worker: &mut Worker, prompts: &[String]) -> Result<Metrics, String> {
    let mut metrics = Metrics::default();
    let n = prompts.len().min(10);
    println!("\n─── Throughput test: {n} prompts (rapid sequential) ───");

    let test_start = Instant::now();
    for prompt in prompts.iter().take(n) {
        let req = SpikeRequest { prompt: prompt.clone(), max_tokens: 64, seed: 42 };
        let start = Instant::now();
        match rpc(&mut worker.stream, &req).await {
            Ok(resp) => {
                let ok = resp.error.is_empty() && !resp.text.is_empty();
                metrics.record(start.elapsed(), resp.elapsed_ms, resp.tokens_generated, ok);
                print!(".");
                if !ok {
                    eprintln!("\nWorker error: {}", resp.error);
                }
            }
            Err(e) => {
                metrics.record(start.elapsed(), 0, 0, false);
                eprintln!("\nRPC error: {e}");
            }
        }
    }
    let total_time = test_start.elapsed();
    println!();
    println!("  Total wall time: {}ms", total_time.as_millis());
    println!("  Throughput: {:.1} prompts/s", n as f64 / total_time.as_secs_f64());
    Ok(metrics)
}

/// 2 workers, round-robin dispatch. Can they coexist?
async fn test_multi(workers: &mut [Worker], prompts: &[String]) -> Result<Metrics, String> {
    let mut metrics = Metrics::default();
    let n_workers = workers.len();
    println!("\n─── Multi-worker test: {n_workers} workers, {} prompts ───", prompts.len());

    for (i, prompt) in prompts.iter().enumerate() {
        let worker_idx = i % n_workers;
        let worker = &mut workers[worker_idx];
        let req = SpikeRequest { prompt: prompt.clone(), max_tokens: 64, seed: 42 };
        let start = Instant::now();
        match rpc(&mut worker.stream, &req).await {
            Ok(resp) => {
                let ok = resp.error.is_empty() && !resp.text.is_empty();
                metrics.record(start.elapsed(), resp.elapsed_ms, resp.tokens_generated, ok);
                if i % 10 == 0 {
                    print!(".");
                }
            }
            Err(e) => {
                metrics.record(start.elapsed(), 0, 0, false);
                eprintln!("\n[{i}/w{worker_idx}] RPC error: {e}");
            }
        }
    }
    println!();
    Ok(metrics)
}

/// 2 workers, kill worker-0 mid-flight, verify worker-1 rescues the prompt.
async fn test_crash(workers: &mut [Worker]) -> Result<Metrics, String> {
    if workers.len() < 2 {
        return Err("Crash test needs at least 2 workers".into());
    }

    let mut metrics = Metrics::default();
    println!("\n─── Crash recovery test ───");

    // Send a prompt to worker-0, then kill it before reading the response
    let prompt = "Explain what fault tolerance means in distributed systems.";
    let req = SpikeRequest { prompt: prompt.to_string(), max_tokens: 128, seed: 42 };

    // Write the request to worker-0
    println!("Sending prompt to worker-0, then killing it...");
    let req_bytes = req.encode_to_vec();
    let req_len = (req_bytes.len() as u32).to_be_bytes();
    workers[0].stream.write_all(&req_len).await.map_err(|e| format!("write len: {e}"))?;
    workers[0].stream.write_all(&req_bytes).await.map_err(|e| format!("write body: {e}"))?;

    // Small delay to let the worker start processing
    tokio::time::sleep(Duration::from_millis(200)).await;

    // Kill worker-0
    workers[0].kill().await?;

    // Attempt to read from worker-0 — should fail
    let mut len_buf = [0u8; 4];
    let read_result = workers[0].stream.read_exact(&mut len_buf).await;
    match read_result {
        Ok(_) => println!("Unexpected: worker-0 responded after kill"),
        Err(e) => println!("Expected: worker-0 stream broken ({e})"),
    }
    metrics.total += 1;

    // Retry on worker-1
    println!("Retrying on worker-1...");
    let start = Instant::now();
    match rpc(&mut workers[1].stream, &req).await {
        Ok(resp) => {
            let ok = resp.error.is_empty() && !resp.text.is_empty();
            metrics.record(start.elapsed(), resp.elapsed_ms, resp.tokens_generated, ok);
            println!("Worker-1 response: {}", resp.text);
            println!(
                "Crash recovery successful! {} tokens in {}ms",
                resp.tokens_generated,
                start.elapsed().as_millis()
            );
        }
        Err(e) => {
            metrics.record(start.elapsed(), 0, 0, false);
            metrics.failed += 1;
            eprintln!("Worker-1 also failed: {e}");
        }
    }

    Ok(metrics)
}

// ── Main ─────────────────────────────────────────────────────────────────────

#[tokio::main]
async fn main() {
    let args = Args::parse();

    println!("═══ Synapse Spike: vLLM Viability Test ═══");
    println!("Test:     {:?}", args.test);
    println!("Workers:  {}", args.workers);
    println!("Prompts:  {}", args.prompts);
    println!("Model:    {}", args.model);
    println!();

    // Spawn workers
    println!("─── Spawning workers ───");
    let mut workers: Vec<Worker> = Vec::new();
    let n = match args.test {
        TestKind::Multi | TestKind::Crash => args.workers.max(2),
        _ => 1,
    };

    for idx in 0..n {
        match Worker::new(idx, &args.model).await {
            Ok(w) => workers.push(w),
            Err(e) => {
                eprintln!("Failed to spawn worker {idx}: {e}");
                // Kill already-spawned workers
                for mut w in workers {
                    let _ = w.kill().await;
                }
                std::process::exit(1);
            }
        }
    }
    println!("All {n} workers ready.\n");

    // Run the selected test
    let prompts = make_prompts(args.prompts);
    let result = match args.test {
        TestKind::Smoke => test_smoke(&mut workers[0]).await,
        TestKind::Sequential => test_sequential(&mut workers[0], &prompts).await,
        TestKind::Concurrent => test_concurrent(&mut workers[0], &prompts).await,
        TestKind::Multi => test_multi(&mut workers, &prompts).await,
        TestKind::Crash => test_crash(&mut workers).await,
    };

    // Report results
    match &result {
        Ok(metrics) => metrics.report("Results"),
        Err(e) => eprintln!("\nTest FAILED: {e}"),
    }

    // Cleanup: kill all workers
    println!("\n─── Cleaning up ───");
    for mut worker in workers {
        let _ = worker.kill().await;
    }
    // Remove socket files
    for idx in 0..n {
        let _ = std::fs::remove_file(socket_path(idx));
    }
    println!("Done.");

    if result.is_err() {
        std::process::exit(1);
    }
}
